import base64
import hashlib

def sign_data(data: str) -> str:
    """
    Временная заглушка для подписи УКЭП.
    В реальности здесь должна быть подпись через КриптоПРО, pycades и т.д.
    Возвращает подпись в формате base64.
    """
    # Пример: имитация подписи через хеш (для тестирования)
    # Реальная подпись должна быть ГОСТ Р 34.10-2012.
    # ВАЖНО: эта заглушка невалидна для API, но позволяет проверить остальной код.
    # Замените на вызов вашего криптопровайдера.
    digest = hashlib.sha256(data.encode('utf-8')).digest()
    return base64.b64encode(digest).decode('utf-8')